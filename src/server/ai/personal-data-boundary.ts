// Граница персональных данных (решение владельца 2026-10-01): всё, что относится
// к кандидату, остаётся внутри контура. Приложение не должно зависеть от передачи
// персональных данных третьей стороне — иначе оно рискует быть запрещённым по
// GDPR и аналогичным законам.
//
// Что это значит практически. Провайдеру можно отправлять текст вакансии —
// это данные о компании-работодателе, не о кандидате. Нельзя отправлять ничего из
// профиля: целевые роли, навыки, страну, часовой пояс, окна доступности, минимум
// оплаты, а также текст CV или письма. Формально «roles + country» само по себе не
// называет человека, но GDPR запрещает обработку данных, позволяющих выделить
// субъекта (singling out), а наш сервер связывает каждый запрос с аккаунтом —
// поэтому владелец выбрал консервативное прочтение.
//
// Зачем отдельный модуль, а не комментарий: комментарий не мешает написать
// `prompt = f(profile)` в следующем роуте. Здесь зафиксировано, какие операции
// вообще невыразимы без персональных данных (`PURPOSES_NEEDING_CANDIDATE_FACTS`),
// и есть единственный конструктор промпта, который можно отдать провайдеру.
// Обе shipped-операции (скоринг релевантности и письма) — в этом списке, поэтому
// обе отказывают: оживить их может локальная модель или решение владельца о более
// узком прочтении, но не «забывчивость» в новом коде. `extraction` (одобрен
// владельцем 2026-10-04) — третья: она читает ТОЛЬКО текст вакансии и потому
// записана с `false` — явной записью пройденного review, а не отсутствием строки.

export class PersonalDataBoundaryError extends Error {
  readonly code = "PERSONAL_DATA_BOUNDARY";
  constructor(code: string = "PERSONAL_DATA_BOUNDARY") { super(code); }
}

/**
 * Операции, которые нельзя выполнить, не отправив провайдеру что-то о кандидате.
 * Значение `true` означает: вызов запрещён, пока персональные данные не остаются
 * внутри контура (локальная модель), либо пока владелец не сузит решение.
 * Значение `false` — явное свидетельство review: операция проверена и читает
 * только данные работодателя (текст вакансии через `buildJobOnlyPrompt`).
 */
export const PURPOSES_NEEDING_CANDIDATE_FACTS: Readonly<Record<string, boolean>> = {
  cover_letter: true,   // письмо пишется про кандидата
  job_matching: true,   // скор «подходит ли кандидату» — про кандидата
  extraction: false,    // поля вакансии из её текста; решение владельца 2026-10-04
};

/**
 * Единственная проверка, которую обязан пройти вызов провайдера, если он собирает
 * запрос из чего-то, кроме текста вакансии. Бросает — молча пропустить нельзя.
 */
export function assertNoCandidateFacts(purpose: string): void {
  if (PURPOSES_NEEDING_CANDIDATE_FACTS[purpose] === true) {
    throw new PersonalDataBoundaryError();
  }
}

/** Что можно отправить: только текст вакансии. Ни одного поля профиля. */
export type JobOnlyFacts = Readonly<{
  title: string;
  company: string;
  description: string;
}>;

/**
 * Единственный конструктор промпта для провайдера, который существует в проекте.
 * Если понадобится новая операция, не требующая данных кандидата, она строится
 * здесь — и тогда она же добавляется в список выше со значением `false`.
 */
export function buildJobOnlyPrompt(facts: JobOnlyFacts, instruction: string): string {
  return `${instruction}\n\nJob title: ${facts.title}\nCompany: ${facts.company}\nDescription: ${facts.description}`;
}
